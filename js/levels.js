  function parseGrid(rows) {
    const grid = [];
    for (let y = 0; y < BC.GRID_SUBTILES; y++) {
      const rowStr = (rows[y] || '').padEnd(BC.GRID_SUBTILES, '.');
      const row = [];
      for (let x = 0; x < BC.GRID_SUBTILES; x++) {
        const ch = rowStr[x] || '.';
        row.push(CHAR_TO_TILE[ch] !== undefined ? CHAR_TO_TILE[ch] : BC.TILE.EMPTY);
      }
      grid.push(row);
    }

    // Clear only solid blocking tiles at spawn boxes (preserve passable FOREST / ICE as in NES ROM)
    const clearSolidRect = (rx, ry, w, h) => {
      for (let y = ry; y < ry + h; y++) {
        for (let x = rx; x < rx + w; x++) {
          if (grid[y] && grid[y][x] !== undefined) {
            const t = grid[y][x];
            if (t === BC.TILE.BRICK || t === BC.TILE.STEEL || t === BC.TILE.WATER) {
              grid[y][x] = BC.TILE.EMPTY;
            }
          }
        }
      }
    };
    clearSolidRect(0, 0, 2, 2);
    clearSolidRect(12, 0, 2, 2);
    clearSolidRect(24, 0, 2, 2);
    clearSolidRect(8, 24, 2, 2);
    clearSolidRect(16, 24, 2, 2);

    // Guarantee Eagle Base & standard initial brick fortress
    for (const [bx, by] of BC.BASE_WALL_COORDS) {
      if (grid[by][bx] === BC.TILE.EMPTY) {
        grid[by][bx] = BC.TILE.BRICK;
      }
    }
    grid[24][12] = BC.TILE.EAGLE;
    grid[24][13] = BC.TILE.EAGLE;
    grid[25][12] = BC.TILE.EAGLE;
    grid[25][13] = BC.TILE.EAGLE;

    return grid;
  }

  const CUSTOM_STORAGE_KEY = 'battle_city_custom_stage_v1';

  BC.TOTAL_CLASSIC_STAGES = RAW_STAGES.length;

  BC.getCustomStage = function () {
    try {
      const raw = global.localStorage.getItem(CUSTOM_STORAGE_KEY);
      if (!raw) return null;
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length === BC.GRID_SUBTILES) {
        return parsed;
      }
    } catch (_) {
      // ignore storage errors
    }
    return null;
  };

  BC.saveCustomStage = function (grid) {
    try {
      global.localStorage.setItem(CUSTOM_STORAGE_KEY, JSON.stringify(grid));
      return true;
    } catch (_) {
      return false;
    }
  };

  BC.hasCustomStage = function () {
    return BC.getCustomStage() !== null;
  };

  BC.getStageGrid = function (stageNumber) {
    if (stageNumber === 0 || stageNumber > BC.TOTAL_CLASSIC_STAGES) {
      const custom = BC.getCustomStage();
      if (custom) {
        return custom.map((r) => r.slice());
      }
    }
    const idx = ((stageNumber - 1) % RAW_STAGES.length + RAW_STAGES.length) % RAW_STAGES.length;
    return parseGrid(RAW_STAGES[idx]);
  };
